"""Composite LangChain callback handler that fans out to multiple handlers."""

from __future__ import annotations

import inspect
from typing import Any
from uuid import UUID

from langchain_core.callbacks import AsyncCallbackHandler
from langchain_core.messages import BaseMessage
from langchain_core.outputs import LLMResult

from src.app.core.common.logging import logger


class LangCallbackHandler(AsyncCallbackHandler):
    """Delegate LangChain callback events to a list of handlers."""

    def __init__(self, handlers: list[AsyncCallbackHandler]) -> None:
        self._handlers = [handler for handler in handlers if handler is not None]

    async def _dispatch(self, method_name: str, *args: Any, **kwargs: Any) -> None:
        for handler in self._handlers:
            method = getattr(handler, method_name, None)
            if method is None:
                continue
            try:
                result = method(*args, **kwargs)
                if inspect.isawaitable(result):
                    await result
            except Exception:
                logger.warning(
                    "lang_callback_handler_dispatch_failed",
                    method=method_name,
                    handler=handler.__class__.__name__,
                    exc_info=True,
                )

    async def on_chain_start(
        self,
        serialized: dict[str, Any],
        inputs: dict[str, Any],
        *,
        run_id: UUID,
        parent_run_id: UUID | None = None,
        tags: list[str] | None = None,
        metadata: dict[str, Any] | None = None,
        **kwargs: Any,
    ) -> None:
        await self._dispatch(
            "on_chain_start",
            serialized,
            inputs,
            run_id=run_id,
            parent_run_id=parent_run_id,
            tags=tags,
            metadata=metadata,
            **kwargs,
        )

    async def on_chain_end(
        self,
        outputs: dict[str, Any],
        *,
        run_id: UUID,
        parent_run_id: UUID | None = None,
        tags: list[str] | None = None,
        metadata: dict[str, Any] | None = None,
        **kwargs: Any,
    ) -> None:
        await self._dispatch(
            "on_chain_end",
            outputs,
            run_id=run_id,
            parent_run_id=parent_run_id,
            tags=tags,
            metadata=metadata,
            **kwargs,
        )

    async def on_chain_error(
        self,
        error: BaseException,
        *,
        run_id: UUID,
        parent_run_id: UUID | None = None,
        tags: list[str] | None = None,
        metadata: dict[str, Any] | None = None,
        **kwargs: Any,
    ) -> None:
        await self._dispatch(
            "on_chain_error",
            error,
            run_id=run_id,
            parent_run_id=parent_run_id,
            tags=tags,
            metadata=metadata,
            **kwargs,
        )

