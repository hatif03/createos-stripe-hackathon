"""Benchmark: plain traced sandbox run vs the full Sandtrap agent on every fixture (hackathon-built).

The plain verdict is computed from the SAME run (install + baseline rounds only), which is exactly what a conventional
dynamic scanner sees. Usage: uv run python scripts/bench.py [fixture ...]
"""
import json
import logging
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
for noisy in ("httpcore", "httpx", "openai", "langfuse", "urllib3", "hpack"):
    logging.getLogger(noisy).setLevel(logging.WARNING)

from src.app.sandtrap.graph import scan  # noqa: E402
from src.app.sandtrap.sandbox import gc  # noqa: E402
from src.app.sandtrap.score import score  # noqa: E402

ROOT = Path(__file__).resolve().parents[1] / "fixtures"
def discover():
    items = {p.name: (str(p), p / "expected.json") for p in sorted(ROOT.iterdir()) if (p / "expected.json").exists() and (p / "setup.py").exists()}
    if (ROOT / "c" / "gated_beacon.c").exists():
        items["elf-gated-beacon"] = (f"c:{ROOT / 'c' / 'gated_beacon.c'}", ROOT / "c" / "expected.json")
    if (ROOT / "npm-postinstall-beacon" / "package.json").exists():
        items["npm-postinstall-beacon"] = (f"npm:{ROOT / 'npm-postinstall-beacon'}", ROOT / "npm-postinstall-beacon" / "expected.json")
    return items


ITEMS = discover()
names = sys.argv[1:] or list(ITEMS)
gc()
rows = []
for name in names:
    target, expected_path = ITEMS[name]
    expected = json.loads(expected_path.read_text()) if expected_path.exists() else {"verdict": "malicious"}
    t = time.time()
    r = None
    error = ""
    for attempt in (1, 2):  # one retry: a transient platform/API hiccup must not hide a real result
        try:
            r = scan(target, out_dir="out/bench", probe_budget=5, remediate=False, use_memory=False)
            break
        except Exception as exc:
            error = f"{type(exc).__name__}: {str(exc)[:120]}"
            print(f"  attempt {attempt} failed: {error}", flush=True)
    if r is not None:
        plain = score([x for x in r.rounds if x.probe.label in ("install", "baseline")])
        rows.append({"fixture": name, "expected": expected["verdict"], "plain": plain.verdict, "sandtrap": r.verdict,
                     "proof": r.confidence, "probes": len([x for x in r.rounds if x.probe.label not in ("install", "baseline")]),
                     "seconds": round(time.time() - t), "job": r.job, "ok": r.verdict == expected["verdict"]})
    else:
        rows.append({"fixture": name, "expected": expected["verdict"], "plain": "-", "sandtrap": "ERROR", "error": error,
                     "probes": 0, "seconds": round(time.time() - t), "ok": False})
    print(rows[-1], flush=True)
print(f"\n{'fixture':22}{'expected':14}{'plain sandbox':16}{'sandtrap':14}{'probes':8}{'sec':6}ok")
for x in rows:
    print(f"{x['fixture']:22}{x['expected']:14}{x['plain']:16}{x['sandtrap']:14}{x.get('probes', 0):<8}{x['seconds']:<6}{'PASS' if x['ok'] else 'FAIL'}")
prev_path = Path("out/bench.json")
if prev_path.exists() and sys.argv[1:]:
    previous = {x["fixture"]: x for x in json.loads(prev_path.read_text())}
    previous.update({x["fixture"]: x for x in rows})
    rows = [previous[n] for n in ITEMS if n in previous]
caught_plain = sum(1 for x in rows if x["expected"] == "malicious" and x["plain"] == "malicious")
caught_agent = sum(1 for x in rows if x["expected"] == "malicious" and x["sandtrap"] == "malicious")
total = sum(1 for x in rows if x["expected"] == "malicious")
print(f"\nmalicious fixtures detected: plain sandbox {caught_plain}/{total}, Sandtrap {caught_agent}/{total}")
Path("out").mkdir(exist_ok=True)
Path("out/bench.json").write_text(json.dumps(rows, indent=2))
print("leftover sandboxes removed:", gc())

