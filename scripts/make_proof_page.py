"""Build docs/PROOF.md from the evidence files in docs/proof/ (hackathon-built). Usage: uv run python scripts/make_proof_page.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
P = ROOT / "docs" / "proof"
bench = json.loads((P / "bench.json").read_text())
real = json.loads((P / "real-world.json").read_text())
doctor = (P / "doctor.txt").read_text().strip()
tests = (P / "unit-tests.txt").read_text().strip().splitlines()[-1]


def cell(slug, ext):
    return f"[{ext}](proof/{slug}.{ext})" if (P / f"{slug}.{ext}").exists() else "-"


demo_meta = [json.loads(m.read_text(encoding="utf-8")) for m in sorted((P / "demo").glob("*/meta.json"))]
ORDER = ["hero", "npm", "elf", "script", "real", "race", "mcp", "mail"]
demo_meta.sort(key=lambda m: ORDER.index(m["name"]) if m["name"] in ORDER else 99)


def dcell(name, f, label):
    return f"[{label}](proof/demo/{name}/{f})" if (P / "demo" / name / f).exists() else "-"


demo_rows = "\n".join(
    f"| {m['title']} | {m['seconds']} s | {dcell(m['name'], 'report.html', 'report')} | {dcell(m['name'], 'sandbox-lifecycle.txt', 'CreateOS sandbox log')} | {dcell(m['name'], 'meta.json', 'meta')} |"
    for m in demo_meta
)
mal = [r for r in bench if r["expected"] == "malicious"]
fx = "\n".join(
    f"| `{r['fixture']}` | {r['expected']} | {r['plain']} | **{r['sandtrap']}** | {r.get('proof', '-')} | {r['probes']} | {r['seconds']} s | "
    f"{cell('fixture-' + r['fixture'], 'html')} / {cell('fixture-' + r['fixture'], 'json')} |"
    for r in bench
)
rw = "\n".join(
    f"| `{x['kind']}:{x['spec'].split('/')[-1]}` | {x['why']} | **{x['verdict']}** | {x.get('score', '-')} | {x.get('probes', '-')} | {x.get('seconds', '-')} s | "
    f"{cell(x['slug'], 'html')} / {cell(x['slug'], 'json')} |"
    for x in real
)
out = f"""# Evidence

Everything here was produced by the code in this repository, on 2026-10-17/18, against live CreateOS sandboxes. The raw reports are committed in
[`docs/proof/`](proof/) (each `.html` opens in a browser and each `.json` is the machine-readable report); the commands to reproduce them are at
the bottom. Nothing in this page is hand-edited: it is generated by `scripts/make_proof_page.py` from those files.

## 1. Real software, not our fixtures

These are public packages and installers, scanned exactly as published (`scripts/real_world.py`). They are **not** known-malicious samples
(those are removed from the registries); the point is to show what Sandtrap says about ordinary, legitimate software, including software that
legitimately uses the network or runs install scripts.

| Target | Why this one | Verdict | Score | Probes | Time | Report |
| --- | --- | --- | --- | --- | --- | --- |
{rw}

Installer scripts and packages that download things by design will trigger network behaviour under the lure; see the
[limitations](../README.md#limitations).

## 2. Our 14 malicious/benign fixtures (the benchmark)

Plain sandbox = the same run scored from the install and baseline rounds only (what a conventional dynamic scanner sees). Sandtrap detected
**{sum(1 for r in mal if r['sandtrap'] == 'malicious')}/{len(mal)}** malicious samples; the plain view **{sum(1 for r in mal if r['plain'] == 'malicious')}/{len(mal)}**. Both clean fixtures stayed clean.

| Fixture | Expected | Plain sandbox | Sandtrap | Proof | Probes | Time | Report |
| --- | --- | --- | --- | --- | --- | --- | --- |
{fx}

Raw table: [proof/bench.json](proof/bench.json), explanation: [BENCHMARK.md](BENCHMARK.md).

## 3. Health checks

Unit tests ([proof/unit-tests.txt](proof/unit-tests.txt)): `{tests}`

`sandtrap doctor` ([proof/doctor.txt](proof/doctor.txt)):

```
{doctor}
```

Stripe Projects state: [proof/stripe-projects-status.txt](proof/stripe-projects-status.txt) (three free services: `createos-project`, `neon-postgres`,
`agentmail-api`; no paid plan).

## 4. Screenshots

Rendered from the files above (full-page captures with headless Edge, `scripts/make_clips.py`).

| | |
| --- | --- |
| [Benchmark: plain sandbox vs Sandtrap](proof/screenshots/benchmark.png) | [Real packages and installers](proof/screenshots/real-world.png) |
| [Public report hosted by a CreateOS sandbox (live URL in the banner)](proof/screenshots/public-report-hosted.png) | [Compiled-binary report with capa](proof/screenshots/elf-report.png) |

## 5. Recorded demo runs (2026-10-20)

Eight runs of the real application, captured with `scripts/record_demo.py` and rendered into videos by `scripts/render_demo.py`. For each: the report (when the run
produces one) and the **CreateOS sandbox log**: the sandbox ids and UTC times of every create, egress change, fork and destroy, taken from the application log.

| Run | Duration | Report | CreateOS sandbox log | Meta |
| --- | --- | --- | --- | --- |
{demo_rows}

## 6. Reproduce

```
uv run python scripts/bench.py                 # 14 fixtures, writes out/bench.json
uv run python scripts/real_world.py            # real PyPI/npm packages and installers, writes docs/proof/
uv run python scripts/record_demo.py           # records the demo runs into docs/proof/demo/\nuv run python scripts/make_proof_page.py       # regenerates this page
uv run pytest tests/unit -q
```
"""
(ROOT / "docs" / "PROOF.md").write_text(out, encoding="utf-8", newline="\n")
print("wrote docs/PROOF.md")
